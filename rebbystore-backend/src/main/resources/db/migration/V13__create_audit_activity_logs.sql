CREATE TABLE audit_activity_logs (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                     actor_username VARCHAR(100),
                                     actor_roles VARCHAR(255),

                                     module_name VARCHAR(60) NOT NULL,
                                     action VARCHAR(40) NOT NULL,

                                     http_method VARCHAR(10) NOT NULL,
                                     request_path VARCHAR(500) NOT NULL,
                                     http_status INTEGER NOT NULL,

                                     outcome VARCHAR(20) NOT NULL,
                                     ip_address VARCHAR(45),
                                     duration_ms BIGINT,

                                     created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                     CONSTRAINT chk_audit_activity_outcome
                                         CHECK (outcome IN ('SUCCESS', 'FAILURE'))
);

CREATE INDEX idx_audit_activity_created_at
    ON audit_activity_logs (created_at DESC);

CREATE INDEX idx_audit_activity_module_date
    ON audit_activity_logs (module_name, created_at DESC);

CREATE INDEX idx_audit_activity_outcome_date
    ON audit_activity_logs (outcome, created_at DESC);

CREATE INDEX idx_audit_activity_actor_date
    ON audit_activity_logs (actor_username, created_at DESC);